// Media type comes from the file's first bytes, never from its extension.
export type ImageMediaType = "image/jpeg" | "image/png" | "image/webp";

export function sniffMediaType(bytes: Uint8Array): ImageMediaType {
  if (bytes.length >= 3 && bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff) return "image/jpeg";
  const png = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];
  if (bytes.length >= 8 && png.every((b, i) => bytes[i] === b)) return "image/png";
  const ascii = (from: number, to: number) => String.fromCharCode(...bytes.slice(from, to));
  if (bytes.length >= 12 && ascii(0, 4) === "RIFF" && ascii(8, 12) === "WEBP") return "image/webp";
  throw new Error("Unrecognised image file: not JPEG, PNG or WebP by its first bytes");
}
